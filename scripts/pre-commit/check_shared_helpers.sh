# Keep the REST/remote-QPU layer DRY: flag new copies of logic that already has
# a shared home. See CodeReuseGuidelines.md for the rules and how to fix them.
#
# Usage:
#   check_shared_helpers.sh FILE...        check the given files (pre-commit)
#   check_shared_helpers.sh --all          check every file the rules cover
#   check_shared_helpers.sh --update-baseline
#                                          rewrite the baseline from the tree
#
# This is a ratchet: existing violations are recorded in the baseline file and
# only an increase in a file's count fails. Fix a violation and lower the
# baseline entry in the same change. A deliberate exception can be marked on
# the offending line with:  // cudaq-lint: allow(<rule>) <reason>

BASELINE=".github/pre-commit/shared_helpers_baseline.txt"

# rule ; path regex (ERE, must match the file path) | line regex (ERE)
RULES=$(cat <<'RULES_END'
local-env-helper;^runtime/(common|cudaq/platform)/.*\.(cpp|h)$;^[[:space:]]*(static[[:space:]]+)?(inline[[:space:]]+)?(const[[:space:]]+)?(std::string|auto)[[:space:]]+(getEnvVar|getValueOrDefault)[[:space:]]*\(
raw-getenv;^runtime/cudaq/platform/default/rest/helpers/.*\.(cpp|h)$;[^A-Za-z_]getenv[[:space:]]*\(
adhoc-poll-sleep;^runtime/(common/Future\.cpp|cudaq/platform/default/rest/helpers/.*\.(cpp|h))$;sleep_for[[:space:]]*\(
executor-downcast;^runtime/cudaq/platform/.*Executor\.cpp$;dynamic_cast<[A-Za-z_:]*ServerHelper[[:space:]]*\*>
RULES_END
)

HINTS=$(cat <<'HINTS_END'
local-env-helper;use cudaq::getEnvVar / cudaq::getValueOrDefault from runtime/common/ConfigUtils.h
raw-getenv;use cudaq::getEnvVar from runtime/common/ConfigUtils.h (or add a variant there)
adhoc-poll-sleep;use pollUntilDone / retryWithDelay from runtime/common/PollingPolicy.h
executor-downcast;get a typed helper from the factory instead of dynamic_cast on ServerHelper
HINTS_END
)

# Print "<count>" of rule matches in a file, skipping comments and allow-marked lines.
count_matches() { # rule file regex
  grep -nE -- "$3" "$2" 2>/dev/null |
    grep -vE '^[0-9]+:[[:space:]]*(//|\*|/\*)' |
    grep -vF "cudaq-lint: allow($1)" | wc -l | tr -d ' '
}

baseline_for() { # rule file
  [ -f "$BASELINE" ] || { echo 0; return; }
  awk -F'\t' -v r="$1" -v f="$2" '$1==r && $2==f {print $3; found=1} END{if(!found)print 0}' "$BASELINE"
}

scan() { # emits "rule<TAB>file<TAB>count" for every non-zero hit among $@
  for file in "$@"; do
    [ -f "$file" ] || continue
    while IFS=';' read -r rule pathre linere; do
      [ -n "$rule" ] || continue
      # The shared helper's own definitions are the one allowed home.
      [ "$rule" = "local-env-helper" ] && [ "$file" = "runtime/common/ConfigUtils.h" ] && continue
      if echo "$file" | grep -qE -- "$pathre"; then
        n=$(count_matches "$rule" "$file" "$linere")
        [ "$n" -gt 0 ] && printf '%s\t%s\t%s\n' "$rule" "$file" "$n"
      fi
    done <<< "$RULES"
  done
}

all_files() {
  git ls-files 'runtime/*.cpp' 'runtime/*.h'
}

case "${1:-}" in
  --update-baseline)
    { echo "# rule<TAB>file<TAB>allowed count. Generated by scripts/pre-commit/check_shared_helpers.sh."
      echo "# Entries may only shrink: fix the violation, then lower or delete the line."
      scan $(all_files) | LC_ALL=C sort; } > "$BASELINE"
    echo "Wrote $BASELINE"; exit 0 ;;
  --all) set -- $(all_files) ;;
esac

EXIT_CODE=0
while IFS=$'\t' read -r rule file n; do
  [ -n "$rule" ] || continue
  allowed=$(baseline_for "$rule" "$file")
  if [ "$n" -gt "$allowed" ]; then
    hint=$(echo "$HINTS" | awk -F';' -v r="$rule" '$1==r {print $2}')
    echo "ERROR [$rule] $file: $n occurrence(s), baseline allows $allowed." >&2
    echo "  Fix: $hint" >&2
    echo "  Exception: add  // cudaq-lint: allow($rule) <reason>  on the line. See CodeReuseGuidelines.md." >&2
    EXIT_CODE=1
  elif [ "$n" -lt "$allowed" ]; then
    echo "NOTE [$rule] $file: now $n, baseline says $allowed. Lower it in $BASELINE." >&2
  fi
done < <(scan "$@")

exit $EXIT_CODE
